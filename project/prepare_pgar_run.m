function run_dir=prepare_pgar_run(run_name,options)
% Freeze a standalone, resumable physics-guided active-identification job.
% This function prepares files only. Windows Task Scheduler launches the job.
if nargin<1,run_name='pgar_nominal_20261029_v1';end
if nargin<2,options=struct();end
root=fileparts(mfilename('fullpath'));addpath(root);cfg=startup_bpil();
assert(~isempty(regexp(run_name,'^[a-zA-Z0-9][a-zA-Z0-9_-]*$','once')), ...
    'pgar:RunName','Use a simple run name without path separators.');
spec=struct('schema','pgar_confirmatory_nominal_v1','run_id',run_name, ...
    'study_role','formal_confirmation', ...
    'job_kind','full_pipeline', ...
    'counts',[600 150 300],'split_seeds',[610101 610102 610103], ...
    'sensor_seed_base',620000,'probe_index',2,'probe_id','probe_02','workers',6, ...
    'range_lower',[.08 .05 -.018],'range_span',[.14 .14 .036], ...
    'train_sizes',[72 240 600],'network_seeds',[630101 630102 630103], ...
    'layers',{{[8],[16 8]}},'lambdas',[.001 .1],'iterations',800,'patience',30, ...
    'scale',[.14 .14 .036],'bootstrap_n',2000,'bootstrap_seed',630990, ...
    'deployment_train_size',600, ...
    'scope','Fixed nominal full-servo simulation; supervised physical initial estimate plus residual NN; planar COM; no online wear adaptation.', ...
    'selection_rule','Validation objects only; retain every predefined initialization; fixed deployment training budget; lock all choices before test inference.', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss''Z''')));
keys=fieldnames(options);
for i=1:numel(keys)
    assert(isfield(spec,keys{i}),'pgar:Option','Unknown option: %s',keys{i});
    spec.(keys{i})=options.(keys{i});
end
assert(numel(spec.counts)==3&&all(spec.counts>=1)&&all(mod(spec.counts,1)==0));
assert(max(spec.train_sizes)<=spec.counts(1)&&ismember(spec.deployment_train_size,spec.train_sizes));
assert(exist('fitrnet','file')==2&&exist('lsqnonlin','file')==2&&exist('rigidBodyTree','class')==8, ...
    'pgar:Toolboxes','Robotics, Optimization and Statistics toolboxes are required.');
required={'run_pgar_job.m','src/pgar_generate_data.m','src/pgar_train_models.m', ...
    'src/pgar_model_predict.m','scripts/pgar_background.ps1','scripts/pgar_task_worker.ps1'};
for i=1:numel(required),assert(isfile(fullfile(root,required{i})),'pgar:Source','Missing %s',required{i});end
run_dir=fullfile(root,'results',run_name);
assert(~exist(run_dir,'dir'),'pgar:Exists','Run already exists; use its Resume command instead of preparing again.');
mkdir(run_dir);snapshot=fullfile(run_dir,'source_snapshot');mkdir(snapshot);
for folder={'src','vendor','scripts','docs'}
    copyfile(fullfile(root,folder{1}),fullfile(snapshot,folder{1}));
end
files=dir(fullfile(root,'*.m'));
for i=1:numel(files),copyfile(fullfile(files(i).folder,files(i).name),snapshot);end
copyfile(fullfile(root,'README.md'),snapshot);
cfg.root=snapshot;
save(fullfile(run_dir,'spec.mat'),'spec');
save(fullfile(run_dir,'configuration.mat'),'cfg','spec');
write_json(fullfile(run_dir,'spec.json'),spec);
write_json(fullfile(run_dir,'status.json'),struct('state','prepared','phase','not_started', ...
    'run_id',spec.run_id,'updated_utc',spec.created_utc,'message','Prepared immutable source snapshot.'));
listing=dir(fullfile(snapshot,'**','*'));listing=listing(~[listing.isdir]);
relative_path=cell(numel(listing),1);sha256=relative_path;bytes=zeros(numel(listing),1);
for i=1:numel(listing)
    path=fullfile(listing(i).folder,listing(i).name);
    relative_path{i}=strrep(path(numel(snapshot)+2:end),'\','/');
    sha256{i}=file_hash(path);bytes(i)=listing(i).bytes;
end
writetable(table(relative_path,sha256,bytes),fullfile(run_dir,'source_manifest.csv'));
fid=fopen(fullfile(run_dir,'RUN_README.txt'),'w','n','UTF-8');assert(fid>=0);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,['Physics-guided active payload identification\nRun: %s\n' ...
    'Scope: fixed nominal full-servo simulation, planar COM.\n' ...
    'Objects: %d training, %d validation, %d independent test.\n' ...
    'Training budgets: %s; deployment budget: %d.\n' ...
    'The launching application can be closed after scheduled-task startup is verified.\n' ...
    'Do not edit source_snapshot, configuration.mat, spec.mat or existing records.\n' ...
    'Progress: process_status.json, status.json, progress_data.json, progress_training.json.\n' ...
    'Results: model_bundle.mat, summary.csv, predictions.csv and COMPLETE.json.\n' ...
    'Each trial/candidate is checkpointed. Resume uses the same frozen configuration.\n' ...
    'Power loss, shutdown or logout can interrupt computation; resume later.\n'], ...
    spec.run_id,spec.counts(1),spec.counts(2),spec.counts(3),mat2str(spec.train_sizes),spec.deployment_train_size);
fprintf('Prepared standalone job: %s\n',run_dir);
end

function value=file_hash(path)
fid=fopen(path,'rb');assert(fid>=0);c=onCleanup(@()fclose(fid)); %#ok<NASGU>
data=fread(fid,Inf,'*uint8');digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(data);value=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end
function write_json(path,value)
temp=[path '.tmp'];fid=fopen(temp,'w','n','UTF-8');assert(fid>=0);
fprintf(fid,'%s\n',jsonencode(value,PrettyPrint=true));fclose(fid);movefile(temp,path,'f');
end
