function run_dir=prepare_pnn_run(run_name,options)
%PREPARE_PNN_RUN Freeze one large-data neural/ridge study before any scoring.
if nargin<1,run_name='pnn_large_training_20261031_v1';end
if nargin<2,options=struct();end
root=fileparts(mfilename('fullpath'));addpath(root);cfg=startup_bpil();
assert(~isempty(regexp(run_name,'^[a-zA-Z0-9][a-zA-Z0-9_-]*$','once')),'pnn:Name','Invalid run name.');
spec=struct('schema','pnn_large_training_v1','run_id',run_name,'smoke_test',false, ...
    'counts',[12000 2000 2000],'split_seeds',[1410101 1410102 1410103], ...
    'sensor_seed_base',14200000,'communication_seed_base',14400000, ...
    'nuisance_seed_base',14500000,'object_id_base',3000000, ...
    'workers',6,'probe_index',2,'probe_id','probe_02', ...
    'range_lower',[.08 .05 -.018],'range_span',[.14 .14 .036], ...
    'scale',[.14 .14 .036],'bounds',[.06 .25;.04 .20;-.025 .025],'gn_lambda',.001, ...
    'network_seeds',[1430101 1430102 1430103], ...
    'nn_layers',{{16,[32 16]}},'nn_lambdas',[1e-6 1e-4 1e-2], ...
    'ridge_lambdas',10.^(-7:0),'skip_alphas',[0 .25 .5 .75 1],'max_epochs',1500,'patience',150, ...
    'checkpoint_every',5,'batch_size',256,'learn_rate',.001, ...
    'adam_beta1',.9,'adam_beta2',.999,'adam_epsilon',1e-8, ...
    'smooth_epsilon',.1,'loss_scales',[.001 .001 .001], ...
    'residual_scale_floor',[1e-5 1e-5 1e-5], ...
    'old_scale',[.14 .14 .036],'old_layers',8,'old_lambda',.001, ...
    'old_iterations',800,'old_patience',30, ...
    'bootstrap_replicates',5000,'bootstrap_seed',1460101, ...
    'required_conditions',{{'nominal','mechanical','electrical','combined'}},'min_eligible_per_condition',100, ...
    'test_generation_after_model_lock',true,'scope','Offline full-servo randomized four-condition study; no hardware or prospective online adaptation claim.', ...
    'created_utc',pnn_utc());
keys=fieldnames(options);
for k=1:numel(keys)
    assert(isfield(spec,keys{k}),'pnn:Option','Unknown option %s.',keys{k});spec.(keys{k})=options.(keys{k});
end
assert(numel(spec.counts)==3&&all(spec.counts>0)&&all(spec.counts==floor(spec.counts)));
assert(spec.workers>=1&&spec.workers<=6&&spec.workers==floor(spec.workers));
if ~spec.smoke_test
    assert(isequal(spec.counts,[12000 2000 2000])&&isequal(spec.split_seeds,[1410101 1410102 1410103]), ...
        'pnn:Protocol','Formal counts/seeds must match the frozen protocol.');
else
    assert(all(spec.split_seeds~=[1410101 1410102 1410103])&&spec.sensor_seed_base~=14200000, ...
        'pnn:SmokeSeeds','Smoke draws must be separate from formal data.');
end
assert(license('test','Neural_Network_Toolbox')&&license('test','Statistics_Toolbox'), ...
    'pnn:Toolbox','Deep Learning and Statistics toolboxes are required.');
assert(exist('lsqnonlin','file')==2&&exist('dlnetwork','class')==8&&exist('parpool','file')==2, ...
    'pnn:Toolbox','Optimization, Deep Learning and Parallel Computing required.');
required={'run_pnn_job.m','src/pnn_plan.m','src/pnn_generate_data.m','src/pnn_cache_dataset.m', ...
    'src/pnn_train.m','src/pnn_predict.m','src/pnn_evaluate.m', ...
    'scripts/pnn_background.ps1','scripts/pnn_resume_guard.ps1','scripts/pgar_task_worker.ps1', ...
    'docs/pnn_large_training_protocol_20261031.txt'};
for k=1:numel(required),assert(isfile(fullfile(root,required{k})),'pnn:Missing','Missing %s.',required{k});end
run_dir=fullfile(root,'results',run_name);assert(~isfolder(run_dir),'pnn:Exists','Existing run: use Resume.');
mkdir(run_dir);snapshot=fullfile(run_dir,'source_snapshot');mkdir(snapshot);
for folder={'src','vendor','scripts','docs','tests'}
    copyfile(fullfile(root,folder{1}),fullfile(snapshot,folder{1}));
end
listing=dir(fullfile(root,'*.m'));
for k=1:numel(listing),copyfile(fullfile(listing(k).folder,listing(k).name),snapshot);end
fid=fopen(fullfile(snapshot,'run_pgar_job.m'),'w');assert(fid>=0);
fprintf(fid,'function run_pgar_job(run_dir)\nrun_pnn_job(run_dir);\nend\n');fclose(fid);
cfg.root=snapshot;
plan=pnn_plan(cfg,spec);
save(fullfile(run_dir,'configuration.mat'),'cfg','spec','-v7.3');
save(fullfile(run_dir,'data_plan.mat'),'-struct','plan','-v7.3');
prc_write_json(fullfile(run_dir,'spec.json'),spec);
writetable(plan.objects,fullfile(run_dir,'objects.csv'));
writetable(plan.manifest,fullfile(run_dir,'manifest.csv'));
copyfile(fullfile(root,'docs','pnn_large_training_protocol_20261031.txt'),fullfile(run_dir,'FROZEN_PROTOCOL.txt'));
listing=dir(fullfile(snapshot,'**','*'));listing=listing(~[listing.isdir]);
relative_path=strings(numel(listing),1);sha256=relative_path;bytes=zeros(numel(listing),1);
for k=1:numel(listing)
    file=fullfile(listing(k).folder,listing(k).name);
    relative_path(k)=strrep(file(numel(snapshot)+2:end),'\','/');
    sha256(k)=prc_file_hash(file);bytes(k)=listing(k).bytes;
end
writetable(table(relative_path,sha256,bytes),fullfile(run_dir,'source_manifest.csv'));
input_path=string(fullfile(run_dir,{'configuration.mat','data_plan.mat','spec.json','FROZEN_PROTOCOL.txt','objects.csv','manifest.csv'})).';
sha256=strings(size(input_path));for k=1:numel(input_path),sha256(k)=prc_file_hash(input_path(k));end
writetable(table(input_path,sha256),fullfile(run_dir,'input_manifest.csv'));
lock=struct('schema','pnn_pre_generation_lock_v1','run_id',run_name,'created_utc',pnn_utc(), ...
    'source_manifest_sha256',prc_file_hash(fullfile(run_dir,'source_manifest.csv')), ...
    'input_manifest_sha256',prc_file_hash(fullfile(run_dir,'input_manifest.csv')), ...
    'plan_signature',plan.plan_signature,'test_not_generated',true);
prc_write_json(fullfile(run_dir,'LOCKED_BEFORE_GENERATION.json'),lock);
prc_write_json(fullfile(run_dir,'status.json'),struct('run_id',run_name,'state','prepared','phase','not_started', ...
    'updated_utc',pnn_utc(),'smoke_test',spec.smoke_test));
fprintf('Prepared PNN %d objects, %d trials: %s\n',height(plan.objects),height(plan.manifest),run_dir);
end
