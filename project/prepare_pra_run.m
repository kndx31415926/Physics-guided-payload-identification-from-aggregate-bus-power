function run_dir=prepare_pra_run(run_name,options)
% Prepare an immutable robustness or reference-assisted continual study.
if nargin<1,run_name='pra_continual_20261030_v1';end
if nargin<2,options=struct();end
root=fileparts(mfilename('fullpath'));addpath(root,fullfile(root,'src'));
assert(~isempty(regexp(run_name,'^[a-zA-Z0-9][a-zA-Z0-9_-]*$','once')));
spec=struct('schema','pra_reference_continual_v1','run_id',run_name,'job_kind','continual', ...
    'source_dir',fullfile(root,'results','pgar_nominal_20261029_v1'), ...
    'lao_dir',fullfile(root,'results','prc_lao_comparison_20261029_v3'), ...
    'robust_source_dir',fullfile(root,'results','prc_holdout_20261029_v1'), ...
    'robust_ids',3:302,'robust_seeds',[910101 910102 910103], ...
    'online_seeds',[920101 920102 920103],'online_iterations',300, ...
    'online_validation_patience',30,'expected_train_references',4,'expected_validation_references',2, ...
    'reference_weight',30,'replay_capacity',32,'nominal_gate_ratio',1.25, ...
    'reference_requires_teacher',false,'stream_seeds',[930101 930102 930103], ...
    'scenarios',{{'stationary','electrical','mechanical','combined'}}, ...
    'blocks',8,'eval_per_block',8,'workers',6,'sensor_seed_base',940000, ...
    'probe_index',2,'probe_id','probe_02','scale',[.14 .14 .036], ...
    'range_lower',[.08 .05 -.018],'range_span',[.14 .14 .036], ...
    'reference_train_theta',[.09 .06 -.014;.21 .07 .014;.10 .18 .012;.20 .17 -.012], ...
    'reference_validation_theta',[.12 .10 -.005;.18 .145 .007], ...
    'retention_ids',3:62,'development_fixture',false, ...
    'study_role','Prespecified stress and continual-update simulation after nominal development.', ...
    'scope','Fixed 4R full-servo plant; m/cx/cz; observable power/encoders/commands; explicitly known reference objects; no unknown evaluation labels in updates.', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss''Z''')));
fields=fieldnames(options);
for i=1:numel(fields),assert(isfield(spec,fields{i}),'pra:Option','Unknown option %s.',fields{i});spec.(fields{i})=options.(fields{i});end
assert(ismember(string(spec.job_kind),["robustness","continual"]));
C=load(fullfile(spec.source_dir,'configuration.mat'),'cfg');cfg=C.cfg;
spec.robust_conditions=pra_perturb_observation('conditions');
assert(isfile(fullfile(spec.source_dir,'COMPLETE.json'))&&isfile(fullfile(spec.lao_dir,'COMPLETE.json')));
assert(isfile(fullfile(spec.robust_source_dir,'COMPLETE.json')));
run_dir=fullfile(root,'results',run_name);assert(~isfolder(run_dir),'pra:Exists','Use Resume for an existing run.');
mkdir(run_dir);snapshot=fullfile(run_dir,'source_snapshot');mkdir(snapshot);
for folder={'src','vendor','scripts','docs'},copyfile(fullfile(root,folder{1}),fullfile(snapshot,folder{1}));end
files=dir(fullfile(root,'*.m'));for i=1:numel(files),copyfile(fullfile(files(i).folder,files(i).name),snapshot);end
copyfile(fullfile(root,'README.md'),snapshot);
fid=fopen(fullfile(snapshot,'run_pgar_job.m'),'w');assert(fid>=0);
fprintf(fid,'function run_pgar_job(run_dir)\nrun_pra_job(run_dir);\nend\n');fclose(fid);
cfg.root=snapshot;save(fullfile(run_dir,'configuration.mat'),'cfg','spec');
prc_write_json(fullfile(run_dir,'spec.json'),spec);
L=dir(fullfile(snapshot,'**','*'));L=L(~[L.isdir]);relative_path=cell(numel(L),1);sha256=relative_path;
for i=1:numel(L)
    f=fullfile(L(i).folder,L(i).name);relative_path{i}=strrep(f(numel(snapshot)+2:end),'\','/');sha256{i}=prc_file_hash(f);
end
writetable(table(relative_path,sha256),fullfile(run_dir,'source_manifest.csv'));
input_path={fullfile(run_dir,'configuration.mat');fullfile(spec.source_dir,'configuration.mat'); ...
    fullfile(spec.source_dir,'model_bundle.mat');fullfile(spec.source_dir,'training_results.mat'); ...
    fullfile(spec.source_dir,'data_plan.mat');fullfile(spec.lao_dir,'models.mat'); ...
    fullfile(spec.robust_source_dir,'data_plan.mat');fullfile(spec.robust_source_dir,'configuration.mat')};
% Only train/validation feature caches are available to the online initializer.
if strcmp(spec.job_kind,'continual')
    for id=1:750,input_path{end+1,1}=fullfile(spec.source_dir,'features',sprintf('trial_%06d.mat',id));end %#ok<AGROW>
    ids=spec.retention_ids;
else,ids=spec.robust_ids;
end
for id=ids(:).',input_path{end+1,1}=fullfile(spec.robust_source_dir,'trials',sprintf('trial_%06d.mat',id));end %#ok<AGROW>
sha256=cellfun(@prc_file_hash,input_path,'UniformOutput',false);
writetable(table(input_path,sha256),fullfile(run_dir,'input_manifest.csv'));
prc_write_json(fullfile(run_dir,'status.json'),struct('state','prepared','phase','not_started','run_id',run_name));
fprintf('Prepared PRA %s: %s\n',spec.job_kind,run_dir);
end
