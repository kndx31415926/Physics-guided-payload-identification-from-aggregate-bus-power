function run_dir=prepare_psf_run(run_name,options)
% Freeze matched steady-input baseline training; reused data are DEVELOPMENT.
if nargin<1,run_name='psf_steady_development_20261030_v1';end
if nargin<2,options=struct();end
root=fileparts(mfilename('fullpath'));addpath(root,fullfile(root,'src'));
assert(~isempty(regexp(run_name,'^[a-zA-Z0-9][a-zA-Z0-9_-]*$','once')),'psf:Name','Invalid run name.');
spec=struct('schema','psf_matched_steady_development_v1','run_id',run_name, ...
    'study_role','DEVELOPMENT_DIAGNOSTIC_REUSED_HOLDOUT', ...
    'source_dir',fullfile(root,'results','pgar_nominal_20261029_v1'), ...
    'holdout_dir',fullfile(root,'results','prc_holdout_20261029_v1'), ...
    'comm_dir',fullfile(root,'results','prt_comm_20261030_v1'),'include_communication',true, ...
    'evaluation_ids',3:302,'validation_limit',150, ...
    'train_sizes',[72 240 600],'network_seeds',[630101 630102 630103], ...
    'layers',{{[8],[16 8]}},'lambdas',[.001 .1],'iterations',800,'patience',30, ...
    'scale',[.14 .14 .036],'probe_id','probe_02','development_fixture',true,'smoke_test',false, ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss''Z''')));
names=fieldnames(options);for i=1:numel(names)
    assert(isfield(spec,names{i}),'psf:Option','Unknown option %s.',names{i});spec.(names{i})=options.(names{i});
end
assert(all(ismember(spec.train_sizes,[72 240 600]))&&numel(unique(spec.train_sizes))==numel(spec.train_sizes), ...
    'psf:Budget','Use available matched budgets 72/240/600.');
assert(all(ismember(spec.network_seeds,[630101 630102 630103]))&&numel(unique(spec.network_seeds))==numel(spec.network_seeds), ...
    'psf:Seed','Use prespecified original NN seeds.');
assert(spec.validation_limit>=2&&spec.validation_limit<=150&&spec.iterations>=1&&spec.patience>=1);
assert(isequal(spec.development_fixture,true)&&strcmp(spec.study_role,'DEVELOPMENT_DIAGNOSTIC_REUSED_HOLDOUT'), ...
    'psf:Development','All PSF runs reuse inspected holdout and must stay development diagnostics.');
if ~spec.smoke_test
    assert(spec.validation_limit==150&&isequal(spec.layers,{[8],[16 8]})&&isequal(spec.lambdas,[.001 .1])&& ...
        spec.iterations==800&&spec.patience==30&&isequal(spec.network_seeds,[630101 630102 630103]), ...
        'psf:Budget','Non-smoke runs preserve the original search and stopping budgets.');
end
assert(isfile(fullfile(spec.source_dir,'COMPLETE.json'))&&isfile(fullfile(spec.holdout_dir,'COMPLETE.json')), ...
    'psf:Source','Completed original training and holdout runs required.');
if spec.include_communication,assert(isfile(fullfile(spec.comm_dir,'COMPLETE.json')),'psf:Source','Complete communication run required.');end
C=load(fullfile(spec.source_dir,'configuration.mat'),'cfg');cfg=C.cfg;
[training,evaluation]=psf_plan(spec);
run_dir=fullfile(root,'results',run_name);assert(~isfolder(run_dir),'psf:Exists','Run exists; use Resume.');
mkdir(run_dir);snapshot=fullfile(run_dir,'source_snapshot');mkdir(snapshot);
for folder={'src','vendor','scripts','docs','tests'},copyfile(fullfile(root,folder{1}),fullfile(snapshot,folder{1}));end
files=dir(fullfile(root,'*.m'));for i=1:numel(files),copyfile(fullfile(files(i).folder,files(i).name),snapshot);end
copyfile(fullfile(root,'README.md'),snapshot);
fid=fopen(fullfile(snapshot,'run_pgar_job.m'),'w');assert(fid>=0);fprintf(fid,'function run_pgar_job(run_dir)\nrun_psf_job(run_dir);\nend\n');fclose(fid);
cfg.root=snapshot;save(fullfile(run_dir,'configuration.mat'),'cfg','spec');
save(fullfile(run_dir,'training_plan.mat'),'training');save(fullfile(run_dir,'evaluation_plan.mat'),'evaluation');
prc_write_json(fullfile(run_dir,'spec.json'),spec);
L=dir(fullfile(snapshot,'**','*'));L=L(~[L.isdir]);relative_path=cell(numel(L),1);sha256=relative_path;
for i=1:numel(L),f=fullfile(L(i).folder,L(i).name);relative_path{i}=strrep(f(numel(snapshot)+2:end),'\','/');sha256{i}=prc_file_hash(f);end
writetable(table(relative_path,sha256),fullfile(run_dir,'source_manifest.csv'));
input_path=[string(fullfile(run_dir,'configuration.mat'));string(fullfile(run_dir,'training_plan.mat')); ...
    string(fullfile(run_dir,'spec.json'));string(fullfile(run_dir,'evaluation_plan.mat'));string(fullfile(spec.source_dir,'training_results.mat')); ...
    string(fullfile(spec.source_dir,'data_plan.mat'));string(fullfile(spec.source_dir,'configuration.mat')); ...
    string(fullfile(spec.holdout_dir,'data_plan.mat'));string(fullfile(spec.holdout_dir,'configuration.mat')); ...
    training.record_path;training.feature_path;evaluation.record_path;evaluation.feature_path];
if spec.include_communication,input_path(end+1)=string(fullfile(spec.comm_dir,'data_plan.mat'));end
input_path=unique(input_path(strlength(input_path)>0),'stable');sha256=cellstr(strings(size(input_path)));
for i=1:numel(input_path),sha256{i}=prc_file_hash(char(input_path(i)));end
writetable(table(input_path,sha256),fullfile(run_dir,'input_manifest.csv'));
prc_write_json(fullfile(run_dir,'status.json'),struct('state','prepared','phase','not_started','run_id',run_name,'development_fixture',true,'smoke_test',spec.smoke_test));
fid=fopen(fullfile(run_dir,'RUN_README.txt'),'w');assert(fid>=0);
fprintf(fid,['DEVELOPMENT DIAGNOSTIC: previously inspected holdout, not independent confirmation.\n' ...
    'Same steady q/P/sdP 48-feature direct NN and ridge; q/P 40-feature NN ablation.\n' ...
    'The same 13 physical features feed ridge residual; stationarity is a common input gate.\n' ...
    'Original residual NN and physics references use identical objects and outputs.\n' ...
    'NN search: same original 2 architectures x 2 penalties, 3 seeds, train budgets.\n' ...
    'Ridge: the same two penalties, deterministic closed-form fit, no architecture search.\n' ...
    'Selected models report available/varying feature dimensions, regression parameters and fit times.\n' ...
    'This is matched observations/data/search choices, not matched parameter counts or runtime.\n' ...
    'Original reference fit time is unavailable (NaN); no new training is attributed to it.\n' ...
    'All new model selection uses training/validation only; lock precedes evaluation loading.\n' ...
    'No new plant data. Future independent confirmation requires fresh frozen test objects.\n' ...
    'Resume via existing scripts/pgar_background.ps1 after any interruption.\n']);fclose(fid);
fprintf('Prepared matched steady-input diagnostic: %s\n',run_dir);
end
