function f=bpil_hefting_features(cfg,obs,scale,probe_id)
%BPIL_HEFTING_FEATURES PGAR residual features from verified hardware plateaus.
% The acquisition adapter owns causal timing and plateau completeness. This
% function reads only the eight measured summaries, never labels or truth.
% Variable hardware timing is not forced into the simulation's fixed bins.
if nargin<4,probe_id='probe_02';end
f=struct('schema','pgar_features_v1','usable',false,'teacher_accepted',false, ...
    'q',nan(1,128),'power',nan(1,40),'residual',nan(1,13), ...
    'base',nan(1,3),'teacher',[],'reasons',{{}},'error_message','');
try
    fields={'schema','acquisition_valid','plateau_q','plateau_P', ...
        'plateau_sd_P','stationary','probe_id'};
    assert(isstruct(obs)&&isscalar(obs)&&all(isfield(obs,fields)), ...
        'bpil:HardwareObservation','Required hardware observation fields are missing.');
    assert(isequal(string(obs.schema),"bpil_hardware_observation_v1")&& ...
        isequal(obs.acquisition_valid,true), ...
        'bpil:HardwareAcquisition','A verified hardware acquisition is required.');
    assert(isscalar(string(obs.probe_id))&&isscalar(string(probe_id))&& ...
        strcmp(string(obs.probe_id),string(probe_id)), ...
        'bpil:HardwareProbe','Wrong probe/order.');
    validateattributes(scale,{'numeric'},{'vector','numel',3,'real','finite','positive'});
    scale=double(scale(:).');
    B=double(cfg.ident.bounds);
    assert(isequal(size(B),[3 2])&&isreal(B)&&all(isfinite(B),'all')&& ...
        all(B(:,2)>B(:,1))&&B(1,1)>0, ...
        'bpil:Bounds','Expected increasing finite 3-by-2 bounds with positive minimum mass.');
    validateattributes(obs.plateau_q,{'numeric'},{'size',[8 4],'real','finite'});
    validateattributes(obs.plateau_P,{'numeric'},{'vector','numel',8,'real','finite'});
    validateattributes(obs.plateau_sd_P,{'numeric'}, ...
        {'vector','numel',8,'real','finite','nonnegative'});
    assert((islogical(obs.stationary)||isnumeric(obs.stationary))&& ...
        isreal(obs.stationary)&&numel(obs.stationary)==8&& ...
        all(obs.stationary(:)==1), ...
        'bpil:HardwareStationarity','All eight observed plateaus must be stationary.');
    measured=struct('plateau_q',double(obs.plateau_q),'plateau_P',double(obs.plateau_P(:)), ...
        'plateau_sd_P',double(obs.plateau_sd_P(:)),'stationary',logical(obs.stationary(:)));
    eta=struct('coefficients',cfg.legacy.power.coefficients);
    teacher=bpil_teacher(cfg,measured,eta,[]);base=double(teacher.theta(:).');
    predicted=bpil_predict_power(cfg,measured.plateau_q,base,eta);
    f.residual=[base./scale,(measured.plateau_P-predicted).'/cfg.ident.power_sigma_W, ...
        teacher.rmse_W,teacher.validation_rmse_W];
    f.base=base;f.teacher=teacher;f.teacher_accepted=logical(teacher.accepted);
    assert(all(isfinite([f.residual f.base])), ...
        'bpil:HardwareFeatures','Nonfinite residual features.');
    % Signal-only q/power features are intentionally unavailable here. They
    % do not enter this residual network or determine residual usability.
    f.usable=true;
    if ~teacher.accepted
        f.reasons=[{'teacher_rejected'},reshape(teacher.diagnostics.reasons,1,[])];
    end
catch err
    f.usable=false;f.reasons={err.identifier};f.error_message=err.message;
end
end
