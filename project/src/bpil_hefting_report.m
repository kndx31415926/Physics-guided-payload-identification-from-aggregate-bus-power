function report=bpil_hefting_report(session_file,output_dir,known_truth)
%BPIL_HEFTING_REPORT Export one saved capture; no device I/O or model fitting.
% known_truth=[mass_kg,com_x_m,com_z_m] is optional caller-supplied independent
% post-hoc information. It never replaces predictions or edits the capture.
if nargin<3,known_truth=[];end
assert((ischar(session_file)||(isstring(session_file)&&isscalar(session_file)))&& ...
    isfile(session_file),'bpil:ReportInput','A saved session MAT file is required.');
assert((ischar(output_dir)||(isstring(output_dir)&&isscalar(output_dir)))&& ...
    strlength(string(output_dir))>0,'bpil:ReportOutput','Specify a new output directory.');
assert(~isfolder(output_dir)&&~isfile(output_dir), ...
    'bpil:ReportExists','Preserve existing exports; specify a new output directory.');
if ~isempty(known_truth)
    validateattributes(known_truth,{'numeric'},{'vector','numel',3,'real','finite'});
    known_truth=double(known_truth(:).');
    assert(known_truth(1)>0,'bpil:ReportTruth','Independent reference mass must be positive.');
end
session_file=char(session_file);output_dir=char(output_dir);
source_hash=prc_file_hash(session_file);A=load(session_file,'session_result');
assert(isfield(A,'session_result'),'bpil:ReportInput','MAT file must contain session_result.');
R=A.session_result;
assert(isstruct(R)&&isscalar(R)&&all(isfield(R,{'schema','session','obs','prediction'}))&& ...
    strcmp(R.schema,'bpil_hefting_session_result_v1'), ...
    'bpil:ReportInput','Expected a saved acquisition result, not a dry-run description.');
S=R.session;O=R.obs;P=R.prediction;
assert(isstruct(O)&&all(isfield(O,{'t','q','P','q_command','plateau_q','plateau_P', ...
    'plateau_sd_P','stationary'})),'bpil:ReportObservation','Missing observation arrays.');
t=double(O.t(:));n=numel(t);
assert(isequal(size(O.q),[n 4])&&isequal(size(O.q_command),[n 4])&&numel(O.P)==n, ...
    'bpil:ReportObservation','Aligned observation dimensions disagree.');
assert(isequal(size(O.plateau_q),[8 4])&&numel(O.plateau_P)==8&& ...
    numel(O.plateau_sd_P)==8&&numel(O.stationary)==8, ...
    'bpil:ReportObservation','Expected eight recorded plateau summaries.');
origin=get(O,'host_time_origin_s',get(S,'motion_start_t',NaN));
[provenance,is_hardware,is_replay,is_mock]=capture_provenance(R);
commands=as_struct(get(S,'commands',{}));raw_power=as_struct(get(S,'raw_power',{}));
ct=zeros(0,1);cr=zeros(0,1);cq=zeros(0,4);
if ~isempty(commands)
    ct=[commands.sent_t].';cq=vertcat(commands.q);
    if isfield(commands,'reference_t'),cr=[commands.reference_t].';else,cr=nan(size(ct));end
end
interval=diff(ct);raw_t=zeros(0,1);raw_w=zeros(0,1);
if ~isempty(raw_power)
    raw_t=[raw_power.sample_t].';raw_w=([raw_power.Vin_V].*[raw_power.Iin_A]).';
end
mkdir(output_dir);
names={'time_from_motion_start_s','host_sample_time_s','q1_rad','q2_rad','q3_rad','q4_rad', ...
    'bus_power_W','issued_q1_rad','issued_q2_rad','issued_q3_rad','issued_q4_rad', ...
    'position_age_from_request_bound_s','power_receive_latency_s','power_received_host_s', ...
    'position_received_host_s','position_request_lower_bound_s','position_sequence'};
aligned=array2table([t,t+origin,double(O.q),double(O.P(:)),double(O.q_command), ...
    column(O,'position_age_s',n),column(O,'power_age_s',n),column(O,'power_received_t',n), ...
    column(O,'position_received_t',n),column(O,'position_sample_t',n), ...
    column(O,'position_sequence',n)],'VariableNames',names);
writetable(aligned,fullfile(output_dir,'aligned_observations.csv'));
windows=get(O,'plateau_windows_host_s',nan(8,2));
assert(isequal(size(windows),[8 2]),'bpil:ReportObservation','Invalid recorded plateau windows.');
plateaus=array2table([(1:8).',double(windows),double(O.plateau_q),double(O.plateau_P(:)), ...
    double(O.plateau_sd_P(:)),double(O.stationary(:)),column(O,'plateau_sample_count',8), ...
    column(O,'plateau_position_count',8)],'VariableNames', ...
    {'pose_index','window_start_host_s','window_end_host_s','q1_rad','q2_rad','q3_rad','q4_rad', ...
    'mean_bus_power_W','std_bus_power_W','stationary','power_sample_count','distinct_position_count'});
writetable(plateaus,fullfile(output_dir,'plateaus.csv'));
interval_column=nan(numel(ct),1);if numel(ct)>1,interval_column(2:end)=interval;end
command_table=table(ct,ct-origin,cr,interval_column, ...
    'VariableNames',{'sent_host_s','sent_from_motion_start_s','reference_s','interval_s'});
writetable(command_table,fullfile(output_dir,'command_timing.csv'));
accepted=isequal(get(P,'accepted',false),true);available=isequal(get(P,'available',false),true);
theta=parameter(P,'theta');candidate=parameter(P,'candidate_theta');raw=parameter(P,'raw');
score=table();
if ~isempty(known_truth)
    err=theta-known_truth;diagnostic=candidate-known_truth;
    score=table(known_truth(1),known_truth(2),known_truth(3),accepted, ...
        err(1),err(2),err(3),hypot(err(2),err(3)), ...
        diagnostic(1),diagnostic(2),diagnostic(3),hypot(diagnostic(2),diagnostic(3)), ...
        'VariableNames',{'independent_mass_kg','independent_com_x_m','independent_com_z_m', ...
        'estimate_accepted','accepted_mass_error_kg','accepted_com_x_error_m','accepted_com_z_error_m', ...
        'accepted_planar_com_error_m','diagnostic_candidate_mass_error_kg', ...
        'diagnostic_candidate_com_x_error_m','diagnostic_candidate_com_z_error_m', ...
        'diagnostic_candidate_planar_com_error_m'});
    writetable(score,fullfile(output_dir,'posthoc_independent_truth_score.csv'));
end
F=figure('Visible','off','Color','w','Position',[50 50 1450 1180]);fc=onCleanup(@()close(F)); %#ok<NASGU>
L=tiledlayout(F,4,1,'TileSpacing','compact','Padding','compact');
title(L,{provenance,'Single-probe capture diagnostic; software provenance is not independent hardware validation'}, ...
    'Interpreter','none','FontWeight','bold','FontSize',15);
ax=nexttile(L);plot(ax,raw_t-origin,raw_w,'Color',[.1 .3 .65],'LineWidth',.85);grid(ax,'on');
ylabel(ax,'Raw bus power (W)');title(ax,'Recorded raw voltage x current; no added smoothing','Interpreter','none');
ax=nexttile(L);colors=lines(4);hold(ax,'on');
for j=1:4,plot(ax,t,double(O.q(:,j)),'Color',colors(j,:),'LineWidth',1);end
for j=1:4,stairs(ax,ct-origin,cq(:,j),'--','Color',colors(j,:),'LineWidth',.75);end
hold(ax,'off');grid(ax,'on');ylabel(ax,'Joint angle (rad)');
legend(ax,{'q1','q2','q3','q4','issued q1','issued q2','issued q3','issued q4'}, ...
    'NumColumns',8,'Location','southoutside');title(ax,'Causally aligned encoders and actual issued targets');
ax=nexttile(L);plot(ax,ct(2:end)-origin,1000*interval,'.-','Color',[.25 .25 .25],'MarkerSize',6);hold(ax,'on');
yline(ax,50,'--','50 ms nominal','Color',[.75 .2 .15]);hold(ax,'off');grid(ax,'on');
ylabel(ax,'Send interval (ms)');title(ax,'Actual host send-to-send intervals; command application is not acknowledged');
ax=nexttile(L);plot(ax,t,1000*column(O,'position_age_s',n),'Color',[.45 .2 .65],'LineWidth',1);hold(ax,'on');
plot(ax,t,1000*column(O,'power_age_s',n),'Color',[.1 .55 .3],'LineWidth',1);hold(ax,'off');grid(ax,'on');
ylabel(ax,'Time (ms)');xlabel(ax,'Seconds from actual motion start');
legend(ax,{'Position age from request lower bound','Power sample-to-receipt latency'},'Location','southoutside');
title(ax,'Recorded timing bounds; position acquisition time is not known exactly');
xvalues=[t;ct-origin;raw_t-origin];xvalues=xvalues(isfinite(xvalues));
if numel(xvalues)>1&&max(xvalues)>min(xvalues)
    axes_list=findall(F,'Type','axes');
    for k=1:numel(axes_list),xlim(axes_list(k),[min(xvalues) max(xvalues)]);end
end
exportgraphics(F,fullfile(output_dir,'capture_diagnostic.png'),'Resolution',180);
exportgraphics(F,fullfile(output_dir,'capture_diagnostic.pdf'),'ContentType','vector');
clear fc
capture_duration=get(S,'ended_t',NaN)-get(S,'started_t',NaN);
motion_duration=get(S,'terminal_command_t',NaN)-get(S,'motion_start_t',NaN);
timing_stats=nan(1,4);if ~isempty(interval),timing_stats=[min(interval),median(interval),prctile(interval,95),max(interval)];end
lines_out={provenance; ...
    'Single recorded probe: acquisition and estimate report, not a repeated-run accuracy study.'; ...
    ['Source MAT: ' session_file];['Source SHA-256: ' source_hash]; ...
    ['Mode: ' char(string(get(R,'mode','unknown')))]; ...
    sprintf('Completed: %d; acquisition valid: %d; accepted estimate: %d; finite candidate available: %d.', ...
    isequal(get(S,'completed',false),true),isequal(get(O,'acquisition_valid',false),true),accepted,available); ...
    ['Session reason: ' char(string(get(S,'reason','unknown')))]; ...
    ['Observation reasons: ' reasons(O)];['Prediction reasons: ' reasons(P)]; ...
    sprintf('Parameters are [mass_kg, com_x_m, com_z_m]. Accepted theta: [%s].',numbers(theta)); ...
    sprintf('Clipped diagnostic candidate: [%s]. Raw ensemble: [%s].',numbers(candidate),numbers(raw)); ...
    'NaN in accepted theta means no deployable estimate; a finite candidate must not override rejection.'; ...
    sprintf('Capture wall duration: %.9g s. Actual first-to-terminal target span: %.9g s.',capture_duration,motion_duration); ...
    sprintf('Nominal reference duration: %.9g s. Inference after acquisition: %.9g s.', ...
    get(S,'reference_duration_s',NaN),get(R,'inference_after_capture_s',NaN)); ...
    sprintf('Raw power samples: %d. Aligned samples: %d. Commands: %d.',numel(raw_power),n,numel(commands)); ...
    sprintf('Command intervals [min,median,p95,max] in seconds: [%s].',numbers(timing_stats)); ...
    sprintf('Monotonic host clock: %s. Motion origin in that clock: %.12g s.', ...
    char(string(get(S,'clock_id','unknown'))),origin); ...
    'Encoder sample_t is the request-time lower bound; its receipt closes the acquisition window.'; ...
    'Position age uses that conservative lower bound. Power receive latency is received_t minus sample_t.'; ...
    'CSV time_from_motion_start_s is recorded power sample time minus actual motion start; no time warping.'; ...
    'UART wire and processing application times are estimates, not device application acknowledgements (non-ACK).'; ...
    'A successful serial write or accepted estimate does not establish true physical application time or accuracy.'; ...
    'Only mass and planar COM x/z are estimated. Transverse COM y is outside this model.'; ...
    'This exporter performs no hardware access, inference, calibration or training; stored predictions are preserved.'};
if isempty(known_truth)
    lines_out=[lines_out;{'No independent known truth was supplied. Accuracy/error is not reported.'}];
else
    err=theta-known_truth;diagnostic=candidate-known_truth;
    lines_out=[lines_out;{ ...
        sprintf('Caller-supplied independent known truth [kg,m,m]: [%s].',numbers(known_truth)); ...
        'Label independence is the caller''s responsibility; truth was not inferred from stored predictions.'; ...
        'These labels are used only for post-hoc scoring in this export; the source record/prediction is not changed.'; ...
        sprintf('Accepted absolute errors [g,mm,mm]: [%s]; planar COM distance %.9g mm.',numbers(abs(err)*1000),hypot(err(2),err(3))*1000); ...
        sprintf('Diagnostic candidate absolute errors [g,mm,mm]: [%s]; these do not validate a rejected estimate.',numbers(abs(diagnostic)*1000)); ...
        'One known object provides a concept demonstration or diagnostic, not population accuracy or a guaranteed error bound.'}];
end
fid=fopen(fullfile(output_dir,'summary.txt'),'w','n','UTF-8');
assert(fid>=0,'bpil:ReportWrite','Cannot create summary.txt.');ff=onCleanup(@()fclose(fid)); %#ok<NASGU>
for k=1:numel(lines_out),fprintf(fid,'%s\n',lines_out{k});end
clear ff
assert(strcmp(source_hash,prc_file_hash(session_file)),'bpil:ReportSourceChanged','The input capture changed during export.');
report=struct('schema','bpil_hefting_report_v1','source_file',session_file,'source_sha256',source_hash, ...
    'output_dir',output_dir,'provenance',provenance,'is_recorded_hardware',is_hardware, ...
    'is_replay',is_replay,'is_mock_or_synthetic',is_mock,'accepted',accepted, ...
    'theta',theta,'candidate_theta',candidate,'known_truth',known_truth,'score',score, ...
    'aligned_sample_count',n,'raw_power_count',numel(raw_power),'command_count',numel(commands), ...
    'command_interval_statistics_s',timing_stats,'source_unchanged',true, ...
    'scope','Saved-record export only; no hardware I/O, training or independent provenance validation.');
save(fullfile(output_dir,'report_metadata.mat'),'report');
end

function [label,hardware,replay,mock]=capture_provenance(R)
S=R.session;H=get(R,'hardware',struct());mode=string(get(R,'mode','unknown'));
mock=isequal(get(S,'is_mock',false),true)||isequal(get(H,'fixture_only',false),true)||mode=="mock";
replay=mode=="replay";
hardware=~mock&&isequal(get(S,'hardware_opened',false),true)&& ...
    (mode=="hardware"||replay)&&isequal(get(S,'hardware_timing_measured',false),true);
if mock,label='MOCK / SYNTHETIC CAPTURE - NOT REAL ROBOT EVIDENCE';
elseif hardware,label='RECORDED HARDWARE CAPTURE - SINGLE CONCEPT DEMONSTRATION';
else,label='UNVERIFIED CAPTURE PROVENANCE - NOT VALIDATED AS HARDWARE';end
if replay,label=['REPLAY OF ' label];end
end
function v=get(S,f,d),if isstruct(S)&&isfield(S,f),v=S.(f);else,v=d;end,end
function A=as_struct(A)
if iscell(A),if isempty(A),A=struct([]);else,A=[A{:}];end,end
end
function v=column(S,name,n)
v=get(S,name,nan(n,1));v=double(v(:));
assert(numel(v)==n,'bpil:ReportObservation','Observation column %s has the wrong length.',name);
end
function p=parameter(S,name)
p=get(S,name,nan(1,3));assert(isnumeric(p)&&isreal(p)&&numel(p)==3, ...
    'bpil:ReportPrediction','Prediction field %s must have three values.',name);p=double(p(:).');
end
function s=numbers(v),s=strtrim(sprintf('%.12g ',v));end
function s=reasons(S)
r=get(S,'reasons',{});s=char(strjoin(string(r),'; '));if isempty(s),s='none recorded';end
end
