function summary=bpil_summarize(outdir)
T=readtable(fullfile(outdir,'episodes.csv'),'TextType','string');
T.mass_error_g=1000*(T.mass_est_kg-T.mass_true_kg);
T.cx_error_mm=1000*(T.cx_est_m-T.cx_true_m);
T.cz_error_mm=1000*(T.cz_est_m-T.cz_true_m);
names=unique(T.method,'stable');blocks=unique(T.block).';S=struct([]);
for b=[0 blocks]
    for j=1:numel(names)
        mask=T.method==names(j);if b>0,mask=mask&T.block==b;end
        R=T(mask,:);valid=logical(R.physical_success)&logical(R.accepted);
        row=struct('block',b,'method',char(names(j)),'n',height(R), ...
            'physical_success_n',sum(R.physical_success),'accepted_n',sum(valid), ...
            'estimated_n',sum(isfinite(R.mass_error_g)), ...
            'mass_mae_g',mean(abs(R.mass_error_g),'omitnan'), ...
            'cx_mae_mm',mean(abs(R.cx_error_mm),'omitnan'),'cz_mae_mm',mean(abs(R.cz_error_mm),'omitnan'), ...
            'mass_max_error_g',max(abs(R.mass_error_g)), ...
            'cx_max_error_mm',max(abs(R.cx_error_mm)),'cz_max_error_mm',max(abs(R.cz_error_mm)), ...
            'accepted_mass_mae_g',mean(abs(R.mass_error_g(valid))), ...
            'accepted_cx_mae_mm',mean(abs(R.cx_error_mm(valid))), ...
            'accepted_cz_mae_mm',mean(abs(R.cz_error_mm(valid))));
        if isempty(S),S=row;else,S(end+1)=row;end %#ok<AGROW>
    end
end
summary=struct2table(S);writetable(summary,fullfile(outdir,'summary.csv'));
f=figure('Visible','off','Position',[100 100 1200 700]);
tiledlayout(2,2,'TileSpacing','compact');
columns={'mass_error_g','cx_error_mm','cz_error_mm'};
labels={'Mass absolute error (g)','COM x absolute error (mm)','COM z absolute error (mm)'};
colors=lines(numel(names));
for k=1:3
    nexttile;hold on;
    for j=1:numel(names)
        R=T(T.method==names(j),:);
        plot(R.episode,abs(R.(columns{k})),'-o','Color',colors(j,:),'MarkerSize',3,'LineWidth',1.2);
    end
    xlabel('Episode (prediction before learning update)');ylabel(labels{k});grid on;
    if k==1,legend(names,'Interpreter','none','Location','best','FontSize',7);end
end
nexttile;axis off;
if any(names=="offline_trained_network")
    notes={'Fixed robot: payload feasibility', ...
        ['Mode: ' char(T.simulation_mode(1))], ...
        'Fixed nominal electrical parameters', ...
        'No online update or empty-arm refitting', ...
        'Transverse COM is not estimated', ...
        'Simulation evidence; no hardware accuracy claim'};
else
    notes={'Physics-guided active payload-identification pilot', ...
        ['Mode: ' char(T.simulation_mode(1))], ...
        'Unknown payload truth: evaluation only', ...
        'Anchor schedule: see saved configuration', ...
        'Transverse COM is not estimated', ...
        'Finite simulated scenarios; no uniform bound'};
end
text(0,1,notes,'VerticalAlignment','top','FontSize',11);
exportgraphics(f,fullfile(outdir,'drift_errors.png'),'Resolution',160);close(f);
disp(summary(summary.block==0,:));
end
