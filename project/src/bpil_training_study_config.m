function s=bpil_training_study_config(options)
% Study settings fixed before validation/test scoring. No hyperparameter search.
s=struct('schema','fixed_probe_equilibrium_training_study_v1', ...
    'train_sizes',[1000 5000],'validation_n',600,'test_n',1000, ...
    'data_seeds',[910031 910032 910033],'network_seeds',[731 732 733], ...
    'direct_layers',[64 32],'residual_layers',[32 16], ...
    'iterations',350,'residual_iterations',250,'lambda',1e-5, ...
    'inverse_max_iterations',100,'inverse_starts',[.5 .5 .5;.2 .8 .8]);
for key=fieldnames(options).'
    assert(isfield(s,key{1}),'bpil:StudyOption','Unknown study option: %s',key{1});s.(key{1})=options.(key{1});
end
assert(all(s.train_sizes>0)&&all(s.train_sizes==round(s.train_sizes)),'bpil:StudySize','Invalid training sizes');
assert(numel(unique(s.data_seeds))==3&&numel(s.data_seeds)==3,'bpil:StudySeeds','Need three separate data seeds');
assert(s.validation_n>0&&s.test_n>0,'bpil:StudySize','Empty validation/test split');
s.train_sizes=sort(unique(s.train_sizes));
s.description=['Fixed nominal robot and probe_02; iid object-level independent train/validation/test. ', ...
    'No drift, online update, servo evidence or test-based model selection. ', ...
    'q noise is independent of object parameters; this study cannot establish servo q-only/P+q value.'];
s.seed_scope='Network initialization variability on one fixed independent object split, not repeated data splits.';
end
