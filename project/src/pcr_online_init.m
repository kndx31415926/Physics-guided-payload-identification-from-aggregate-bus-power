function state=pcr_online_init(cfg,spec)
%PCR_ONLINE_INIT Independent deterministic residual-ridge comparison state.
% Only original nominal train/validation caches and frozen model selection
% are read. No unknown drift/test observations or labels are loaded here.
assert(isfield(spec,'source_dir')&&isfield(spec,'pcr_ridge_source_file'), ...
    'pcr:Source','Nominal source_dir and explicit pcr_ridge_source_file required.');
spec=defaults(spec);r=char(spec.source_dir);
A=load(fullfile(r,'model_bundle.mat'),'bundle');b=A.bundle;
assert(strcmp(b.schema,'pgar_residual_bundle_v1')&&b.train_budget==600, ...
    'pcr:Source','Expected original 600-object nominal metadata.');
assert(isequaln(cfg.sim,b.cfg.sim)&&isequaln(cfg.ident.bounds,b.cfg.ident.bounds)&& ...
    isequaln(cfg.legacy.power.coefficients,b.power_coefficients), ...
    'pcr:Configuration','Nominal simulation/bounds/calibration must match.');
Q=load(spec.pcr_ridge_source_file,'models');models=Q.models;
assert(strcmp(models.schema,'psf_models_v1')&&~models.test_used_for_selection, ...
    'pcr:Source','Expected previously selected PSF models.');
bi=find(models.spec.train_sizes==600);assert(isscalar(bi),'pcr:Source','600-object ridge required.');
learner=models.students{bi,4,1};
assert(strcmp(learner.kind,'ridge')&&strcmp(learner.selection.method,'physics_residual_ridge13')&& ...
    learner.selection.train_budget==600&&learner.selection.seed==0&& ...
    learner.selection.lambda==learner.model.lambda&&learner.model.lambda==.001, ...
    'pcr:Selection','The frozen 600-object residual ridge/lambda changed.');
assert(isequaln(models.spec.scale,b.scale)&&strcmp(models.spec.probe_id,b.probe_id), ...
    'pcr:Configuration','Ridge target scales and probe must match PCU.');
P=load(fullfile(r,'data_plan.mat'),'objects');O=P.objects;
train_ids=double(b.training_object_ids(:));val_ids=double(b.validation_object_ids(:));
assert(isequal(train_ids,(1:600).')&&isequal(val_ids,(601:750).')&& ...
    models.train_used(bi)==600&&models.validation_used==150, ...
    'pcr:Source','Exact common 600/150 object partitions are required.');
train=read_partition(r,O,train_ids,'train');validation=read_partition(r,O,val_ids,'validation');
columns=std(train.X,0,1)>1e-10;
assert(isequal(logical(learner.columns),columns)&&numel(columns)==13, ...
    'pcr:Preprocessing','Original varying-feature selection differs from common inputs.');
target=(train.theta-train.base)./b.scale;
refit=psf_ridge('fit',train.X(:,columns),target,learner.model.lambda);
[weighted,fitreport]=pcr_weighted_ridge(train.X(:,columns),target,ones(600,1),learner.model);
Xcheck=[train.X;validation.X];p0=psf_ridge('predict',learner.model,Xcheck(:,columns));
p1=psf_ridge('predict',refit,Xcheck(:,columns));p2=psf_ridge('predict',weighted,Xcheck(:,columns));
coeferr=max(abs([refit.beta(:)-learner.model.beta(:);refit.intercept(:)-learner.model.intercept(:)]));
preerr=max(abs([refit.mu(:)-learner.model.mu(:);refit.sigma(:)-learner.model.sigma(:)]));
pred_error=max(abs(p0-p1),[],'all');weighted_error=max(abs(p0-p2),[],'all');
assert(preerr<1e-12&&coeferr<1e-10&&pred_error<1e-10&&weighted_error<1e-10, ...
    'pcr:InitialParity','Frozen PSF ridge does not reproduce on exact PCU nominal inputs.');
state=struct('schema','pcr_online_residual_ridge_v1','cfg',cfg,'spec',spec, ...
    'scale',b.scale,'bounds',b.known_bounds,'probe_id',b.probe_id, ...
    'eta0',struct('coefficients',b.power_coefficients),'frozen_models',{{learner}}, ...
    'bootstrap',train,'validation',validation,'block_count',0,'history',{{}}, ...
    'processed_keys',{{}},'replay',struct([]), ...
    'source_bundle_sha256',prc_file_hash(fullfile(r,'model_bundle.mat')), ...
    'ridge_source_sha256',prc_file_hash(spec.pcr_ridge_source_file), ...
    'source_manifest',struct('training_ids',train_ids,'validation_ids',val_ids, ...
        'test_records_loaded',false,'test_features_loaded',false), ...
    'initial_parity',struct('preprocessing_max_abs_error',preerr, ...
        'coefficient_max_abs_error',coeferr,'prediction_max_abs_error',pred_error, ...
        'weighted_uniform_prediction_max_abs_error',weighted_error,'weighted_fit_report',fitreport));
[raw,~]=pcr_model_prediction(state.frozen_models,validation.X,validation.base,state.scale,state.bounds);
state.initial_nominal_raw_loss=mean(((raw-validation.theta)./state.scale).^2,'all');
for name={'frozen','empty_only','gated_calibration','gated_full'}
    state.systems.(name{1})=struct('eta',state.eta0,'models',{state.frozen_models}, ...
        'deployed_updates',0,'eta_updates',0,'network_updates',0);
end
state.scope=['Deterministic residual ridge with frozen original mask/mu/sigma/lambda. ', ...
    'Same PCU data/calibration/replay/gates; nominal retention relative to this ridge initial model. ', ...
    'Known references only. NN restandardizes during refitting whereas this ridge does not.'];
end

function S=defaults(S)
d=struct('reference_weight',30,'replay_capacity',32,'nominal_gate_ratio',1.25, ...
    'reference_requires_teacher',false,'expected_train_references',4,'expected_validation_references',2, ...
    'gate_min_relative_improvement',.05,'gate_min_absolute_improvement',1e-6, ...
    'gate_component_mae_tolerance',[.00015 .0005 .0005], ...
    'gate_worst_relative_tolerance',.05,'gate_worst_absolute_tolerance',1e-6, ...
    'pcu_keep_history',true,'pcu_use_offline',true);
for f=fieldnames(d).',if ~isfield(S,f{1}),S.(f{1})=d.(f{1});end,end
assert(S.reference_weight>0&&S.replay_capacity>=S.expected_train_references&& ...
    S.nominal_gate_ratio>=1&&S.gate_min_relative_improvement>=0&&S.gate_min_relative_improvement<=1&& ...
    S.gate_min_absolute_improvement>=0&&S.gate_worst_relative_tolerance>=0&&S.gate_worst_absolute_tolerance>=0&& ...
    numel(S.gate_component_mae_tolerance)==3&&all(isfinite(S.gate_component_mae_tolerance))&& ...
    all(S.gate_component_mae_tolerance>=0),'pcr:Spec','Invalid frozen adaptation settings.');
end

function D=read_partition(root,O,ids,role)
[found,rows]=ismember(ids,double(O.object_id));assert(all(found),'pcr:Source','Missing nominal IDs.');
O=O(rows,:);assert(all(string(O.split)==string(role)),'pcr:Source','Nominal split mismatch.');
D=struct('X',nan(numel(ids),13),'base',nan(numel(ids),3), ...
    'theta',[O.mass_kg O.cx_m O.cz_m],'object_ids',ids,'role',role,'cache_sha256',{{}});
for i=1:numel(ids)
    tid=ids(i);if ismember('trial_id',O.Properties.VariableNames),tid=O.trial_id(i);end
    file=fullfile(root,'features',sprintf('trial_%06d.mat',tid));A=load(file,'cached');c=A.cached;
    assert(c.key.object_id==ids(i)&&strcmp(c.key.split,role)&&c.status.physical_success&&c.features.usable, ...
        'pcr:Source','Invalid original training/validation cache.');
    D.X(i,:)=c.features.residual;D.base(i,:)=c.features.base;D.cache_sha256{i,1}=prc_file_hash(file);
end
assert(all(isfinite([D.X D.base D.theta]),'all'),'pcr:Source','Nonfinite nominal inputs.');
end
