function [model,report]=pcr_weighted_ridge(X,Y,weights,template)
%PCR_WEIGHTED_RIDGE Weighted residual ridge in fixed offline coordinates.
% Minimize sum_i w_i*||Y_i-Z_i*B-b||^2/sum(w) + lambda*||B||_F^2.
% Z uses the original PSF mu/sigma; the intercept b is unpenalized. The
% original feature mask and selected lambda are never reselected online.
assert(isstruct(template)&&isscalar(template)&&strcmp(template.schema,'psf_ridge_v1'), ...
    'pcr:Ridge','An original PSF ridge preprocessing/model template is required.');
X=double(X);Y=double(Y);weights=double(weights(:));
assert(ismatrix(X)&&ismatrix(Y)&&size(X,1)==size(Y,1)&&size(X,1)>=2&& ...
    size(Y,2)==3&&numel(weights)==size(X,1)&&all(isfinite([X Y]),'all')&& ...
    all(isfinite(weights))&&all(weights>=0)&&sum(weights>0)>=2&&isfinite(sum(weights)), ...
    'pcr:Ridge','Invalid training rows, targets or weights.');
mu=double(template.mu(:).');sigma=double(template.sigma(:).');lambda=double(template.lambda);
assert(numel(mu)==size(X,2)&&numel(sigma)==size(X,2)&&all(isfinite([mu sigma]))&& ...
    all(sigma>0)&&isscalar(lambda)&&isfinite(lambda)&&lambda>0, ...
    'pcr:Ridge','Invalid frozen preprocessing or penalty.');
Z=(X-mu)./sigma;wn=weights/sum(weights);zm=wn.'*Z;ym=wn.'*Y;
Zc=Z-zm;Yc=Y-ym;A=Zc.'*(Zc.*wn)+lambda*eye(size(X,2));rhs=Zc.'*(Yc.*wn);
B=A\rhs;intercept=ym-zm*B;
assert(all(isfinite([B(:);intercept(:)])),'pcr:Ridge','Nonfinite ridge solution.');
model=struct('schema','psf_ridge_v1','mu',mu,'sigma',sigma,'intercept',intercept, ...
    'beta',B,'lambda',lambda);
residual=Z*B+intercept-Y;
report=struct('schema','pcr_weighted_ridge_fit_v1','training_n',size(X,1), ...
    'positive_weight_n',sum(weights>0),'weight_sum',sum(weights),'lambda',lambda, ...
    'objective',sum(wn.*sum(residual.^2,2))+lambda*sum(B.^2,'all'), ...
    'relative_normal_equation_residual',norm(A*B-rhs,'fro')/max(1,norm(rhs,'fro')), ...
    'weighted_intercept_gradient_norm',norm(wn.'*residual), ...
    'preprocessing','original offline feature mask/mu/sigma, unchanged', ...
    'validation_targets_used',false,'deterministic',true);
md=javaMethod('getInstance','java.security.MessageDigest','SHA-256');
md.update(unicode2native(jsonencode(model),'UTF-8'));
report.model_sha256=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
