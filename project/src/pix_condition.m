function C=pix_condition(S,family,severity,seed)
%PIX_CONDITION Label-independent synthetic nuisance draw.
assert(any(strcmp(char(family),S.families)),'pix:Family','Unknown family.');
assert(isscalar(severity)&&any(abs(severity-S.severities)<1e-12), ...
    'pix:Severity','Severity must be one of the prespecified levels.');
validateattributes(seed,{'numeric'},{'scalar','integer','>=',0,'<',2^32});
r=RandStream('mt19937ar','Seed',double(seed));
% Draw all fields regardless of family so paired families share departures.
f=.8+.4*rand(r,1,27);phase=2*pi*rand(r);
mech=severity*double(any(strcmp(char(family),{'mechanical','combined'})));
elec=severity*double(any(strcmp(char(family),{'electrical','combined'})));
M=S.mechanical_endpoint;E=S.electrical_endpoint;
C=struct('schema','pix_condition_v1','family',char(family), ...
    'severity',double(severity),'nuisance_seed',double(seed), ...
    'link_mass_scale',1+mech*M.link_mass_departure.*f(1:3), ...
    'link_com_offset_m',mech*M.com_offset_m.*f(1:3).', ...
    'viscous_scale',1+mech*M.viscous_departure.*f(4:7), ...
    'coulomb_scale',1+mech*M.coulomb_departure.*f(8:11), ...
    'stribeck_Nm',mech*M.stribeck_Nm.*f(8:11), ...
    'gain_scale',1+mech*M.gain_departure.*f(12:15), ...
    'resistance_scale',1+elec*E.resistance_departure.*f(16:19), ...
    'initial_temperature_C',S.ambient_C+elec*E.initial_temperature_rise_K.*f(20:23), ...
    'alpha_per_K',elec*S.copper_alpha_per_K, ...
    'bridge_drop_V',elec*E.bridge_drop_V.*f(24:27), ...
    'bridge_resistance_ohm',elec*E.bridge_resistance_ohm.*f(24:27), ...
    'auxiliary_offset_W',elec*E.auxiliary_offset_W, ...
    'auxiliary_ripple_W',elec*E.auxiliary_ripple_W, ...
    'auxiliary_ripple_Hz',E.auxiliary_ripple_Hz,'ripple_phase',phase);
C.scope=['Fixed within-probe nuisance except endogenous current/temperature ', ...
    'and prescribed time-varying auxiliary draw. No payload arguments.'];
end
