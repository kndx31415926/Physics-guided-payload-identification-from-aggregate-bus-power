function expected=pnn_expected_record(plan,i)
%PNN_EXPECTED_RECORD Immutable identity derived only from the frozen plan.
row=plan.manifest(i,:);o=plan.objects(row.object_index,:);spec=plan.spec;
communication=struct('command_delay_s',[.010 .015],'encoder_delay_s',[.010 .015],'seed',row.communication_seed);
expected=struct('schema',plan.schema,'run_id',spec.run_id,'plan_signature',plan.plan_signature, ...
    'trial_id',row.trial_id,'object_id',row.object_id,'split',char(row.split),'probe_id',plan.probe.id, ...
    'probe_index',spec.probe_index,'theta_true',[o.mass_kg o.cx_m o.cz_m], ...
    'sensor_seed',row.sensor_seed,'communication',communication,'condition',char(row.condition), ...
    'condition_index',row.condition_index,'nuisance_seed',row.nuisance_seed, ...
    'generative_condition',plan.conditions(i));
end
