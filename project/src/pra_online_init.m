function state=pra_online_init(cfg,spec)
% Initialize known-reference continual PGAR. No test feature/record is read.
assert(isstruct(spec)&&isfield(spec,'source_dir'),'pra:Source','source_dir is required.');
spec=defaults(spec);r=char(spec.source_dir);
A=load(fullfile(r,'model_bundle.mat'),'bundle');b=A.bundle;
assert(strcmp(b.schema,'pgar_residual_bundle_v1')&&b.train_budget==600&&numel(b.models)==3, ...
    'pra:Source','Expected the frozen 600-object three-seed PGAR bundle.');
assert(isequaln(cfg.sim,b.cfg.sim)&&isequaln(cfg.ident.bounds,b.cfg.ident.bounds), ...
    'pra:Configuration','Nominal timing and parameter bounds must match the source.');
assert(isequaln(cfg.legacy.power.coefficients,b.power_coefficients), ...
    'pra:Configuration','Initialization must use nominal source coefficients, never plant drift.');
P=load(fullfile(r,'data_plan.mat'),'objects');O=P.objects;
train_ids=double(b.training_object_ids(:));val_ids=double(b.validation_object_ids(:));
assert(numel(train_ids)==600&&numel(val_ids)==150&&isempty(intersect(train_ids,val_ids)), ...
    'pra:Source','Expected disjoint 600 train / 150 validation IDs.');
train=read_partition(r,O,train_ids,'train');validation=read_partition(r,O,val_ids,'validation');
state=struct('schema','pra_online_known_reference_v1','cfg',cfg,'spec',spec, ...
    'scale',b.scale,'bounds',b.known_bounds,'probe_id',b.probe_id, ...
    'eta0',struct('coefficients',b.power_coefficients),'frozen_models',{b.models}, ...
    'bootstrap',train,'validation',validation,'block_count',0,'history',{{}}, ...
    'processed_keys',{{}},'source_bundle_sha256',prc_file_hash(fullfile(r,'model_bundle.mat')), ...
    'source_manifest',struct('training_ids',train_ids,'validation_ids',val_ids, ...
    'test_records_loaded',false,'test_features_loaded',false), ...
    'scope','Periodic independent known-reference supervision; no unknown/test truth updates.');
[~,p]=pra_online_model_prediction(b.models,validation.X,validation.base,b.scale,b.known_bounds);
initial=zeros(1,3);for s=1:3,initial(s)=loss(p(:,:,s),validation.theta,b.scale);end
for name={'network_only','full','no_replay'}
    state.variants.(name{1})=struct('models',{b.models},'initial_nominal_loss',initial, ...
        'initial_nominal_ensemble_loss',loss(mean(p,3),validation.theta,b.scale), ...
        'replay',empty_replay(size(train.X,2)),'attempted_updates',0,'deployed_seed_updates',zeros(1,3));
end
end

function S=defaults(S)
d=struct('online_seeds',[920101 920102 920103],'online_iterations',300, ...
    'reference_weight',30,'replay_capacity',32,'nominal_gate_ratio',1.25, ...
    'reference_requires_teacher',false,'online_validation_patience',30, ...
    'expected_train_references',4,'expected_validation_references',2);
for f=fieldnames(d).',if ~isfield(S,f{1}),S.(f{1})=d.(f{1});end,end
assert(numel(S.online_seeds)==3&&all(isfinite(S.online_seeds))&&all(S.online_seeds==fix(S.online_seeds)), ...
    'pra:Seeds','Exactly three fixed integer online seeds are required.');
assert(S.online_iterations>=1&&S.replay_capacity>=S.expected_train_references&& ...
    S.reference_weight>0&&S.nominal_gate_ratio>=1,'pra:Spec','Invalid training budget/gates.');
assert(isscalar(S.reference_requires_teacher)&&ismember(S.reference_requires_teacher,[false true]), ...
    'pra:Spec','reference_requires_teacher must be logical.');
end

function D=read_partition(root,O,ids,role)
[found,rows]=ismember(ids,double(O.object_id));assert(all(found),'pra:Source','Missing source IDs.');
O=O(rows,:);assert(all(string(O.split)==string(role)),'pra:Source','Source split mismatch.');
D=struct('X',nan(numel(ids),13),'base',nan(numel(ids),3), ...
    'theta',[O.mass_kg O.cx_m O.cz_m],'object_ids',ids,'role',role,'cache_sha256',{{}});
for i=1:numel(ids)
    tid=ids(i);if ismember('trial_id',O.Properties.VariableNames),tid=O.trial_id(i);end
    file=fullfile(root,'features',sprintf('trial_%06d.mat',tid));A=load(file,'cached');c=A.cached;
    assert(c.key.object_id==ids(i)&&strcmp(c.key.split,role)&& ...
        c.status.physical_success&&c.features.usable,'pra:Source','Invalid source cache.');
    D.X(i,:)=c.features.residual;D.base(i,:)=c.features.base;
    D.cache_sha256{i,1}=prc_file_hash(file);
end
assert(all(isfinite([D.X D.base D.theta]),'all'),'pra:Source','Nonfinite source inputs.');
end
function R=empty_replay(n)
R=struct('X',zeros(0,n),'base',zeros(0,3),'theta',zeros(0,3), ...
    'record_key',{{}},'record_hash',{{}},'calibration',{{}},'block_key',{{}});
end
function v=loss(p,t,s),v=mean(((p-t)./s).^2,'all');end
