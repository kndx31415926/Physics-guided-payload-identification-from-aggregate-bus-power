function state=prb_online_init(cfg,spec)
%PRB_ONLINE_INIT Development-only joint calibration/network acceptance state.
% The original nominal training/validation caches stay in their nominal
% feature coordinate system. Online reference observations are retained raw
% and their physics features are recomputed under each candidate calibration.
spec=defaults(spec);old=pra_online_init(cfg,spec);
state=rmfield(old,'variants');state.schema='prb_joint_system_development_v1';
state.spec=spec;state.replay=struct([]);
[raw,~]=pra_online_model_prediction(state.frozen_models,state.validation.X, ...
    state.validation.base,state.scale,state.bounds);
state.initial_nominal_raw_loss=mean(((mean(raw,3)-state.validation.theta)./state.scale).^2,'all');
for name={'frozen','empty_only','gated_calibration','gated_full'}
    state.systems.(name{1})=struct('eta',state.eta0,'models',{state.frozen_models}, ...
        'deployed_updates',0,'eta_updates',0,'network_updates',0);
end
state.scope=['Development on previously inspected streams; independent known references only. ', ...
    'Whole-system gates compare current-reference predictions before changing eta or weights. ', ...
    'Nominal retention gate constrains weights on eta0 cached inputs, not current drifting measurements.'];
end

function S=defaults(S)
d=struct('online_seeds',[970101 970102 970103],'online_iterations',300, ...
    'reference_weight',30,'replay_capacity',32,'nominal_gate_ratio',1.25, ...
    'reference_requires_teacher',false,'online_validation_patience',30, ...
    'expected_train_references',4,'expected_validation_references',2, ...
    'gate_min_relative_improvement',.05,'gate_min_absolute_improvement',1e-6, ...
    'gate_component_mae_tolerance',[.00015 .0005 .0005], ...
    'gate_worst_relative_tolerance',.05,'gate_worst_absolute_tolerance',1e-6);
for f=fieldnames(d).',if ~isfield(S,f{1}),S.(f{1})=d.(f{1});end,end
assert(S.gate_min_relative_improvement>=0&&S.gate_min_relative_improvement<=1&& ...
    S.gate_min_absolute_improvement>=0&&S.gate_worst_relative_tolerance>=0&& ...
    S.gate_worst_absolute_tolerance>=0,'prb:GateSpec','Invalid acceptance margins.');
assert(numel(S.gate_component_mae_tolerance)==3&&all(isfinite(S.gate_component_mae_tolerance))&& ...
    all(S.gate_component_mae_tolerance>=0),'prb:GateSpec','Expected three finite component tolerances.');
end
