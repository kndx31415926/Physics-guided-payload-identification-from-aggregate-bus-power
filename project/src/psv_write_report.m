function psv_write_report(run_dir,spec,S,I,info)
fid=fopen(fullfile(run_dir,'RESULTS_CN.txt'),'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'冻结模型的新对象确认与结构失配压力测试\n运行：%s\n',spec.run_id);
if spec.smoke_test,fprintf(fid,'工程SMOKE；不是论文正式结果。\n');end
fprintf(fid,'新对象%d；条件%d；完整伺服案例%d；物理失败%d；异常%d。\n',info.unique_objects,info.condition_count,info.planned_cases,info.physical_failed,info.exceptions);
fprintf(fid,['所有模型在数据生成前冻结；未按本批测试选择模型，未重新训练。每条件同对象、同噪声、同通信流配对。\n' ...
    '失配是预定机械参数变化及额外绝对/四次力矩电损耗压力模型；不是实物标定规律，也不是完全独立仿真器。\n' ...
    '以下600训练预算、原三种子集成/确定性模型、共同裁剪，全有限预测评分；覆盖率另列，拒绝不能删除有限误差。\n' ...
    '质量g；cx、cz和平面COM距离mm。raw结果、所有单种子和72/240训练量见summary.csv。\n\n']);
Q=S(S.train_budget==600&S.model_seed==0&S.postprocessing=="common_clip",:);
for k=1:height(Q),fprintf(fid,'%s / %s: mass %.6g, cx %.6g, cz %.6g, planar %.6g；finite %d/%d；accepted %d/%d；bounds %.4g\n', ...
        Q.condition(k),Q.method(k),Q.mass_mae_g(k),Q.cx_mae_mm(k),Q.cz_mae_mm(k),Q.planar_com_mean_distance_mm(k),Q.finite_n(k),Q.planned_cases(k),Q.accepted_n(k),Q.planned_cases(k),Q.bounds_hit_rate(k));end
fprintf(fid,'\n预定主要比较（残差NN减直接q/P NN40，负值偏向残差NN）：\n');P=I(I.primary_comparison,:);
for k=1:height(P),fprintf(fid,'%s: 差值 %.6g，配对物体bootstrap 95%%区间 [%.6g, %.6g]，有效配对%d/%d。\n',P.metric(k),P.mean_difference(k),P.ci_lower(k),P.ci_upper(k),P.finite_pair_n(k),P.planned_pair_n(k));end
fprintf(fid,['\n区间以对象为重采样单位，不把模型种子当独立样本；缺失时只用共同有限配对并披露数量。\n' ...
    '次要与压力比较的未校正区间仅作描述，不作多个检验的整体显著性声明。\n' ...
    '必须结合残差ridge判断NN的额外必要性；不因复杂方案预设其更好，负结果全部保留。\n' ...
    'Lao三组是同平台方法移植，不复现原作者硬件精度，输入和伺服结构差异不能隐藏。\n' ...
    '所有精度限于仿真、当前载荷域和平面质心；真实机械臂数据尚未采集。\n']);
end
